/* Régression métiers hors réseau : node tests/test_invoice_v2.js */
const assert=require('node:assert/strict');
global.Calc=require('../v2/calc.js');
const Invoice=require('../v2/invoice.js');
const Storage=require('../v2/storage-tools.js');
const issuer={name:'Entreprise BTP Réelle',address:'1 rue du Bâtiment',city:'75001 Paris',siret:'12345678901234',insurer:'Assurance test',email:'contact@btp.fr',payment:'Virement à 30 jours'};
function devis(id='q1'){return{id,status:'signed',num:'D2026-100',client:{name:'Client',addr:'2 rue de Paris'},obj:'Travaux',site:'Paris',lines:[{label:'Peinture',qty:2,unit:'m²',price:75}],tva:20,demo:false};}
assert.equal(Invoice.isValidIssuer(issuer),true);
assert.equal(Invoice.isValidIssuer({...issuer,siret:'000 000 000 00000 (fictif)'}),false);
const simulated=Invoice.issue({...devis(),demo:true},[],{name:'Société fictive',address:'Lyon',city:'Lyon',siret:'000 000 000 00000 (fictif)'},new Date('2026-11-07T12:00:00Z'));
assert.equal(simulated.invoice.num,'DEMO-F2026-001');
assert.equal(simulated.invoice.demo,true);
assert.equal(Invoice.nextNumber([simulated],2026), 'F2026-001','La numérotation réelle reste indépendante de la démonstration');
assert.equal(Invoice.nextNumber([simulated],2026,true), 'DEMO-F2026-002');
assert.equal(Invoice.issuerProblems({...issuer,siret:'000 000 000 00000 (fictif)'}).includes('SIRET réel (14 chiffres)'),true);
assert.throws(()=>Invoice.issue({...devis(),status:'draft'},[],issuer),/accord/);
const a=Invoice.issue(devis(),[],issuer,new Date('2026-11-07T12:00:00Z'));
assert.equal(a.invoice.num,'F2026-001');
assert.equal(a.invoice.totals.ttc,180);
assert.equal(a.invoice.quoteNumber,'D2026-100');
assert.equal(Invoice.nextNumber([a],2026),'F2026-002');
assert.equal(Invoice.balance(a),180);
// Reproduction : devis confirmé « acompte reçu » → facture avec acompte au crédit.
const newlySigned=devis('deposit-actual');
const actualDeposit=Invoice.recordDeposit(newlySigned,'42,50','2026-11-06','Virement');
assert.equal(actualDeposit.status,'deposit');
assert.equal(Invoice.paid(actualDeposit),42.50);
assert.equal(newlySigned.status,'signed','Le devis original ne doit pas être modifié');
const actualBill=Invoice.issue(actualDeposit,[],issuer,new Date('2026-11-07T12:00:00Z'));
assert.equal(Invoice.paid(actualBill),42.50,'Le montant réel remplace le forfait de 30 %');
assert.equal(Invoice.balance(actualBill),137.50);
assert.equal(actualBill.payments.length,1,'Ne jamais doubler un acompte enregistré');
assert.throws(()=>Invoice.recordDeposit(newlySigned,'500','2026-11-06','Carte'),/dépasse/);
assert.throws(()=>Invoice.recordDeposit(newlySigned,'0','2026-11-06','Carte'),/valide/);
assert.throws(()=>Invoice.recordDeposit(newlySigned,'12','2026-02-31','Carte'),/Date/);
const paidDeposit={...devis('deposit-1'),status:'deposit',depositAt:'2026-11-06T15:30:00Z'};
const billWithDeposit=Invoice.issue(paidDeposit,[a],issuer,new Date('2026-11-07T12:00:00Z'));
assert.equal(billWithDeposit.status,'invoiced');
assert.equal(billWithDeposit.invoice.num,'F2026-002');
assert.equal(billWithDeposit.invoice.totals.ttc,180);
assert.equal(billWithDeposit.payments.length,1);
assert.equal(billWithDeposit.payments[0].kind,'deposit');
assert.equal(billWithDeposit.payments[0].date,'2026-11-06');
assert.equal(Invoice.paid(billWithDeposit),54,'Acompte déjà payé de 30 %');
assert.equal(Invoice.balance(billWithDeposit),126,'Seul le solde doit rester à payer');
assert.equal(paidDeposit.status,'deposit','Le devis d’origine n’est pas muté');
assert.equal(Invoice.issue({...paidDeposit,demo:true},[],{name:'Fictif'},new Date('2026-11-07T12:00:00Z')).invoice.demo,true);
assert.throws(()=>Invoice.issue(billWithDeposit,[a],issuer),/existe déjà/);
// Ne pas doubler un acompte qui figure déjà dans des paiements enregistrés.
const previouslyPaid={...devis('deposit-2'),status:'deposit',depositAt:'2026-11-06T15:30:00Z',payments:[{amount:54,date:'2026-11-06',method:'Virement'}]};
const alreadyCredited=Invoice.issue(previouslyPaid,[],issuer);
assert.equal(Invoice.paid(alreadyCredited),54);
assert.equal(alreadyCredited.payments.length,1);
const partialPaid={...devis('deposit-3'),status:'deposit',payments:[{amount:30,date:'2026-11-06',method:'Virement'}]};
const complemented=Invoice.issue(partialPaid,[],issuer);
assert.equal(Invoice.paid(complemented),54);
assert.equal(Invoice.balance(complemented),126);
const p=Invoice.addPayment(a,50,'2026-11-07','Virement');
assert.equal(Invoice.paid(p),50);
assert.equal(Invoice.balance(p),130);
assert.equal(Invoice.balance(a),180,'La création de paiement ne doit pas modifier la facture source');
assert.throws(()=>Invoice.addPayment(p,150,'2026-11-07','Virement'),/dépasse/);
assert.throws(()=>Invoice.addPayment(p,-1,'2026-11-07','Carte'),/Montant/);
assert.throws(()=>Invoice.addPayment(p,1,'2026-02-31','Carte'),/Date/);
const paid=Invoice.addPayment(p,130,'2026-11-07','Carte');assert.equal(Invoice.balance(paid),0);
const backup={format:'renov-express-v2-backup',version:1,devis:[a],tarifs:[],company:issuer};
assert.equal(Storage.validate(backup),true);
assert.equal(Storage.validate({...backup,devis:[simulated]}),true,'Une simulation doit pouvoir être sauvegardée');
assert.equal(Storage.merge([{...devis('q2'),id:'q2'}],backup).length,2);
assert.throws(()=>Storage.merge([{...devis('q2'),id:'q2',invoice:{num:'F2026-001'}}],backup),/Numéro de facture/);
assert.throws(()=>Storage.validate({...backup,devis:[a,a]}),/dupliqué/);
assert.throws(()=>Storage.validate({...backup,devis:[{...a,signature:{data:'x\" onerror=\"alert(1)'}}]}),/Signature de sauvegarde invalide/);
assert.throws(()=>Storage.validate({...backup,devis:[{...a,invoice:{num:'F2026-001'}}]}),/Données de facture invalides/);
assert.throws(()=>Storage.validate({...backup,devis:[{...a,payments:[{amount:-100,method:'Espèces'}]}]}),/Règlements invalides/);

console.log('Factures, paiements et sauvegardes : tests réussis.');
